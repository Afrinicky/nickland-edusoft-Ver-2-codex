//
//   node scripts/schema-to-postgres.mjs
//
// The school's database is defined once, in electron/db/database.js, and that
// definition is the offline system's. The online system must hold the SAME
// school — every table, every column, every constraint — or the two are not
// the same product and a sync between them is a translation exercise that goes
// wrong quietly.
//
// So this does not re-declare anything. It BUILDS the offline database in
// memory — the CREATE statements and every migration, exactly as a school's PC
// runs them — then reads the result back out of sqlite_master and renders it
// as Postgres. The generated file is checked in so a reviewer can read it, and
// regenerated whenever the offline schema changes. A column added on the
// desktop appears online by re-running this, not by remembering to.
//
// What is translated, and why:
//
//   INTEGER PRIMARY KEY AUTOINCREMENT  →  BIGINT GENERATED BY DEFAULT AS IDENTITY
//       "BY DEFAULT", not "ALWAYS": a row synchronised from a school's own
//       desktop arrives WITH its id, and that id is what every other table
//       already points at.
//   REAL      →  DOUBLE PRECISION      the same binary float the desktop has,
//                                      so a balance cannot differ by a penny
//                                      between the two systems.
//   TEXT DEFAULT CURRENT_TIMESTAMP  →  the same 'YYYY-MM-DD HH:MM:SS' string
//                                      SQLite writes, so string comparisons on
//                                      timestamps keep working.
//
// Every school gets its own Postgres SCHEMA holding this whole set of tables.
// That is what makes the reuse honest: the offline schema has no school_id
// column and does not need one, and no query can reach across two schools by
// forgetting a WHERE clause, because the two schools are not in the same table.

import { DatabaseSync } from 'node:sqlite';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'cloud-python/schema/school.sql');
const SEED_OUT = resolve(ROOT, 'cloud-python/schema/seed.sql');

const { SCHEMA, runMigrations, seedDefaults } = require(resolve(ROOT, 'electron/db/database.js'));

// ── build the offline database, exactly as a school's PC does ────────────────
function buildOffline() {
  const db = new DatabaseSync(':memory:');
  db.transaction = (fn) => (...a) => {
    db.exec('BEGIN');
    try { const r = fn(...a); db.exec('COMMIT'); return r; }
    catch (e) { db.exec('ROLLBACK'); throw e; }
  };
  db.exec(SCHEMA);
  runMigrations(db);
  return db;
}

// ── SQLite DDL → Postgres DDL ───────────────────────────────────────────────

// SQLite's CURRENT_TIMESTAMP writes 'YYYY-MM-DD HH:MM:SS' into a TEXT column.
// Postgres' would write a timestamptz literal, which sorts and compares
// differently as text — so the format is reproduced rather than assumed.
const NOW_TEXT = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";

function convertColumnType(sql) {
  return sql
    // The identity column. Must come before the bare INTEGER rule.
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi,
             'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\b(?!\s*\()/gi,
             'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    // Money and marks. The desktop stores them as SQLite REAL, which is an
    // IEEE double; DOUBLE PRECISION is the same thing, so a figure cannot
    // change value by crossing between the systems.
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
    .replace(/\bBLOB\b/gi, 'BYTEA')
    // Foreign keys reference BIGINT identity columns now.
    .replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/\bNUMERIC\b/gi, 'NUMERIC')
    .replace(/DEFAULT\s+CURRENT_TIMESTAMP/gi, `DEFAULT ${NOW_TEXT}`)
    .replace(/DEFAULT\s+\(datetime\('now'\)\)/gi, `DEFAULT ${NOW_TEXT}`)
    .replace(/datetime\('now'\)/gi, `${NOW_TEXT}`);
}

// Comments come out FIRST, before anything is split.
//
// The schema documents its columns in place — `template_type TEXT NOT NULL,
// -- 'fees', 'books', 'canteen', 'other'` — and those comments contain commas
// and brackets. Splitting first and stripping afterwards tore that line into
// four definitions, three of them a bare quoted word, and Postgres said so.
function stripComments(sql) {
  return sql.replace(/\/\*[\s\S]*?\*\//g, '').replace(/--[^\n]*/g, '');
}

// SQLite tolerates a trailing comma before a constraint and writes some
// constraints inline; Postgres wants them tidy. Splitting on top-level commas
// (not the ones inside parentheses) is enough for this schema.
function splitDefinitions(body) {
  const parts = [];
  let depth = 0, current = '';
  for (const ch of body) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { parts.push(current); current = ''; continue; }
    current += ch;
  }
  if (current.trim()) parts.push(current);
  return parts.map(p => p.trim()).filter(Boolean);
}

// Foreign keys are lifted OUT of the CREATE and re-attached at the end.
//
// SQLite does not care what order tables are created in; Postgres refuses a
// reference to a table that does not exist yet, and the school's tables refer
// to each other in both directions (a user has a staff row, a staff row has a
// designation, a designation is held by users). Sorting them topologically
// works right up until the first cycle somebody adds. Attaching every
// constraint afterwards works always, and reads better besides: the tables are
// the school, and the constraints are what ties it together.
function convertTable(name, sql) {
  const open = sql.indexOf('(');
  const close = sql.lastIndexOf(')');
  const body = stripComments(sql.slice(open + 1, close));
  const columns = [];
  const foreignKeys = [];
  let n = 0;

  for (const def of splitDefinitions(body)) {
    const clean = def.replace(/\s+/g, ' ').trim();
    if (!clean) continue;
    if (/^FOREIGN\s+KEY/i.test(clean)) {
      n += 1;
      foreignKeys.push(
        `ALTER TABLE ${name} ADD CONSTRAINT ${name}_fk_${n} ${convertColumnType(clean)};`);
      continue;
    }
    columns.push(convertColumnType(clean));
  }

  return {
    table: `CREATE TABLE IF NOT EXISTS ${name} (\n  ${columns.join(',\n  ')}\n);`,
    foreignKeys,
  };
}

function convertIndex(sql) {
  // SQLite and Postgres agree on the shape of a plain CREATE INDEX; only the
  // IF NOT EXISTS needs guaranteeing.
  let out = sql.trim();
  if (!/IF NOT EXISTS/i.test(out)) {
    out = out.replace(/CREATE\s+(UNIQUE\s+)?INDEX\s+/i, (m, u) => `CREATE ${u || ''}INDEX IF NOT EXISTS `);
  }
  return out.endsWith(';') ? out : out + ';';
}

// ── render ──────────────────────────────────────────────────────────────────
function render(db) {
  const rows = db.prepare(`
    SELECT type, name, sql FROM sqlite_master
    WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
    ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name
  `).all();

  const tables = rows.filter(r => r.type === 'table');
  const indexes = rows.filter(r => r.type === 'index');

  const converted = tables.map(t => convertTable(t.name, t.sql));
  const head = `-- Nickland Edusoft — one school's database, for Postgres.
--
--   GENERATED FILE. Do not edit by hand.
--   Regenerate with:  node scripts/schema-to-postgres.mjs
--
-- Rendered from the offline system's own schema (electron/db/database.js) by
-- building it in memory — CREATE statements and every migration, exactly as a
-- school's PC runs them — and reading the result back out. The online system
-- therefore holds the same school as the desktop does: same tables, same
-- columns, same constraints. A column added on the desktop appears here by
-- re-running the generator, not by somebody remembering to.
--
-- Applied INTO A PER-SCHOOL POSTGRES SCHEMA. Every school has its own, holding
-- this whole set of tables. That is what makes reusing the offline schema
-- honest: it has no school_id column and does not need one, and no query can
-- reach across two schools by forgetting a WHERE clause, because two schools
-- are never in the same table.
--
-- ${tables.length} tables, ${indexes.length} indexes.

`;

  const body = [
    ...converted.map(c => c.table),
    '',
    '-- ── how the school ties together ──',
    '-- Attached after the tables so the order they were created in cannot',
    '-- matter, and so a reference added later needs no reordering.',
    'DO $$ BEGIN',
    ...converted.flatMap(c => c.foreignKeys).map(fk => `  ${fk}`),
    'EXCEPTION WHEN duplicate_object THEN NULL; END $$;',
    '',
    '-- ── indexes ──',
    ...indexes.map(i => convertIndex(i.sql)),
  ].join('\n');

  return head + body + '\n';
}

// ── what a brand-new school starts with ─────────────────────────────────────
// The designations and their access ladder, the classes from Pre-Nursery to
// JHS 3, the subjects, the grading bands, the notification templates and the
// settings. All of it comes from `seedDefaults` — the offline system's own
// idea of what a Ghanaian basic school looks like on day one — rather than
// from a second list here that would drift from it within a release.
const SEEDED_TABLES = [
  'designations', 'designation_permissions', 'academic_years', 'terms',
  'class_groups', 'subjects', 'class_subjects', 'grading_bands',
  'notification_templates', 'settings',
];

function quote(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

function renderSeed(db) {
  const lines = [];
  let rows = 0;
  for (const table of SEEDED_TABLES) {
    let all;
    try { all = db.prepare(`SELECT * FROM ${table}`).all(); } catch (_) { continue; }
    if (!all.length) continue;
    const cols = Object.keys(all[0]);
    lines.push(`-- ${table} (${all.length})`);
    for (const row of all) {
      lines.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map(c => quote(row[c])).join(', ')}) ON CONFLICT DO NOTHING;`);
      rows++;
    }
    // Every identity sequence has to be wound past the ids just inserted, or
    // the first row a school adds collides with a seeded one.
    if (cols.includes('id')) {
      lines.push(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), (SELECT COALESCE(MAX(id), 1) FROM ${table}));`);
    }
    lines.push('');
  }
  return { sql: `-- Nickland Edusoft — what a new school starts with.
--
--   GENERATED FILE. Do not edit by hand.
--   Regenerate with:  node scripts/schema-to-postgres.mjs
--
-- Dumped from the offline system's own \`seedDefaults\` (electron/db/database.js)
-- after building the schema in memory, so a school provisioned online opens on
-- exactly the designations, classes, subjects, grading bands and settings a
-- school provisioned on a desktop does.
--
-- ${rows} rows across ${SEEDED_TABLES.length} tables.

${lines.join('\n')}`, rows };
}

const db = buildOffline();
const sql = render(db);
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, sql);

seedDefaults(db);
const seed = renderSeed(db);
writeFileSync(SEED_OUT, seed.sql);

const tableCount = (sql.match(/CREATE TABLE/g) || []).length;
const indexCount = (sql.match(/CREATE (UNIQUE )?INDEX/g) || []).length;
console.log(`Wrote ${OUT}`);
console.log(`  ${tableCount} tables, ${indexCount} indexes, ${sql.split('\n').length} lines.`);
console.log(`Wrote ${SEED_OUT}`);
console.log(`  ${seed.rows} seed rows.`);
